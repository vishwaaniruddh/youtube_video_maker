for s in scenes:
    out_mp3 = os.path.join(AUDIO_DIR, f"scene_{s['id']:02d}.mp3")
    print(f"Generating audio for Scene {s['id']}...")
    subprocess.run([
        "edge-tts",
        "--voice", "hi-IN-MadhurNeural",
        "--rate=+5%",
        "--text", s["text"],
        "--write-media", out_mp3
    ], check=True)
    print(f"  Scene {s['id']} audio saved: {os.path.getsize(out_mp3)} bytes")

